"""Inference round-trip: checkpoint -> module -> Prediction over a dataset split."""

from __future__ import annotations

import numpy as np
import pytest
import torch

from injection_hse.config import MeasurementConfig
from injection_hse.evaluation.inference import Prediction, load_se_module, predict_dataset

SENSORS = ["Bus R4", "Bus C5", "Bus I2"]
ORDERS = [1, 3, 5]


def test_load_se_module_round_trip(trained_run, eval_grid):
    ckpt, dataset = trained_run
    module = load_se_module(ckpt, grid=eval_grid, dataset_path=dataset, device="cpu")
    # the normalizer travelled with the checkpoint and is fitted (the loss needs it)
    assert module.normalizer.cartesian_scale is not None
    assert list(module.orders) == ORDERS
    assert not module.training  # eval mode


def test_predict_dataset_shapes_and_mask(trained_run, eval_grid):
    ckpt, dataset = trained_run
    module = load_se_module(ckpt, grid=eval_grid, dataset_path=dataset, device="cpu")
    measurement = MeasurementConfig(voltage_nodes=SENSORS, slack_known=True)
    pred = predict_dataset(
        module,
        source_or_path=dataset,
        grid=eval_grid,
        measurement=measurement,
        split="val",
        device="cpu",
    )
    assert isinstance(pred, Prediction)
    assert pred.target_v.shape == pred.pred_v.shape
    assert pred.target_v.ndim == 3  # [S, H, N]
    assert pred.n_orders == len(ORDERS)
    assert pred.mask.shape == (pred.n_samples, pred.n_rows)
    assert pred.mask.dtype == np.bool_
    # the placement mask observes EXACTLY the sensor rows (same every sample)
    observed = np.flatnonzero(pred.mask[0])
    assert np.array_equal(np.sort(observed), np.sort(pred.observed_rows))
    assert pred.mask.all(axis=0).sum() == len(pred.observed_rows)
    # the per-unit error is finite and non-negative
    err = pred.abs_error_pu()
    assert err.shape == pred.target_v.shape
    assert np.isfinite(err).all() and (err >= 0).all()


