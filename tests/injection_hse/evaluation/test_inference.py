def test_predict_dataset_inherits_checkpoint_split(trained_run, eval_grid):
    """predict_dataset on a PATH uses the checkpoint's own split settings, not the defaults.

    The ``trained_run`` fixture trained with ``val_fraction=0.3`` (≠ the DataConfig default
    ``0.1``). A path-based ``predict_dataset`` must reproduce the exact val scenario set the run
    trained against; the old code built a bare ``DataConfig`` and silently fell back to 0.1,
    letting "val" rows overlap the training set.
    """
    from injection_hse.data import ParquetDataset

    ckpt, dataset = trained_run
    module = load_se_module(ckpt, grid=eval_grid, dataset_path=dataset, device="cpu")
    assert module.cfg.data.val_fraction != 0.1  # the run used a non-default split
    measurement = MeasurementConfig(voltage_nodes=SENSORS, slack_known=True)

    pred_path = predict_dataset(
        module,
        source_or_path=dataset,
        grid=eval_grid,
        measurement=measurement,
        split="val",
    )

    # a source built with the CHECKPOINT's split (val_fraction + split_seed) sees the same set
    src_match = ParquetDataset(
        dataset,
        grid=eval_grid,
        val_fraction=module.cfg.data.val_fraction,
        seed=module.cfg.data.split_seed,
    )
    pred_match = predict_dataset(
        module,
        source_or_path=src_match,
        grid=eval_grid,
        measurement=measurement,
        split="val",
    )
    assert pred_path.n_samples == pred_match.n_samples
    assert np.array_equal(pred_path.target_v, pred_match.target_v)

    # the OLD behaviour (default val_fraction=0.1) would pick a DIFFERENT, smaller val set
    src_default = ParquetDataset(dataset, grid=eval_grid, val_fraction=0.1, seed=0)
    pred_default = predict_dataset(
        module,
        source_or_path=src_default,
        grid=eval_grid,
        measurement=measurement,
        split="val",
    )
    assert pred_default.n_samples != pred_path.n_samples


def test_predict_dataset_split_full_includes_every_row(
    trained_run, eval_grid, eval_dataset
):
    """split="full" evaluates EVERY surviving scenario, unlike "all" (which excludes test).

    Simulates evaluating a checkpoint on an entirely EXTERNAL dataset (e.g. one generated by
    an independent reference engine) via a hand-built ``ParquetDataset`` with its OWN
    val/test split — independent of the checkpoint's own training split settings, exactly
    the scenario ``split="full"`` exists for.
    """
    from injection_hse.data import ParquetDataset

    ckpt, _ = trained_run
    module = load_se_module(
        ckpt, grid=eval_grid, dataset_path=eval_dataset, device="cpu"
    )
    measurement = MeasurementConfig(voltage_nodes=SENSORS, slack_known=True)

    src = ParquetDataset(
        eval_dataset, grid=eval_grid, val_fraction=0.2, seed=1, test_fraction=0.3
    )
    n_train = len(src.train_dataset())
    n_val = len(src.val_dataset())
    n_test = len(src.test_dataset())
    assert n_test > 0  # the split genuinely carves out a held-out test set

    pred_full = predict_dataset(
        module,
        source_or_path=src,
        grid=eval_grid,
        measurement=measurement,
        split="full",
    )
    pred_all = predict_dataset(
        module, source_or_path=src, grid=eval_grid, measurement=measurement, split="all"
    )

    assert pred_full.n_samples == n_train + n_val + n_test
    assert pred_all.n_samples == n_train + n_val
    assert (
        pred_all.n_samples < pred_full.n_samples
    )  # "all" excludes the held-out test rows


