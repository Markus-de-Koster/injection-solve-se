def test_infer_no_grad_and_eval(trained_run, eval_grid):
    ckpt, dataset = trained_run
    module = load_se_module(ckpt, grid=eval_grid, dataset_path=dataset, device="cpu")
    from injection_hse.data import build_data_source
    from injection_hse.data import StateCollate

    src = build_data_source(module.cfg.data, grid=eval_grid)
    batch = StateCollate()([src.val_dataset()[0]])
    out = module.infer(batch)
    assert set(out) == {"pred_v", "target_v", "mask", "order_mask"}
    assert out["pred_v"].shape[-1] == out["mask"].shape[-1]
    assert out["mask"].dtype == torch.bool
    # nothing on the tape (inference is off the autograd path)
    assert not out["pred_v"].requires_grad


def test_predict_dataset_records_each_samples_scenario(
    trained_run, eval_grid, eval_dataset
):
    """``scenario_index`` names the dataset scenario of every sample of every split."""
    from injection_hse.data import ParquetDataset

    ckpt, _ = trained_run
    module = load_se_module(
        ckpt, grid=eval_grid, dataset_path=eval_dataset, device="cpu"
    )
    measurement = MeasurementConfig(voltage_nodes=SENSORS, slack_known=True)
    src = ParquetDataset(
        eval_dataset, grid=eval_grid, val_fraction=0.2, seed=1, test_fraction=0.3
    )
    pred = predict_dataset(
        module,
        source_or_path=src,
        grid=eval_grid,
        measurement=measurement,
        split="test",
    )
    assert pred.scenario_index.dtype == np.int64
    expected = [int(item["index"]) for item in src.test_dataset()]
    assert pred.scenario_index.tolist() == expected


def test_prediction_metrics_by_group_scores_each_group_alone():
    from dataclasses import replace

    from injection_hse.evaluation import prediction_metrics, prediction_metrics_by_group

    rng = np.random.default_rng(0)
    s, h, n = 6, 2, 4
    target = rng.normal(size=(s, h, n)) + 1j * rng.normal(size=(s, h, n))
    pred = Prediction(
        target_v=target,
        pred_v=target + 0.01 * rng.normal(size=(s, h, n)),
        mask=np.tile(np.array([True, False, False, True]), (s, 1)),
        orders=[1, 3],
        base_v=np.ones(n),
        node_ids=np.arange(n, dtype=np.int64),
        phase_codes=np.zeros(n, dtype=np.int64),
        observed_rows=np.array([0, 3], dtype=np.int64),
        sensor_names=[],
        grid=None,
        # three scenarios with two steps each
        scenario_index=np.repeat(np.arange(3, dtype=np.int64), 2),
    )
    groups = np.array([7, 9, 7])  # scenario -> group
    by_group = prediction_metrics_by_group(pred, groups)
    assert list(by_group) == [7, 9]
    sel = np.isin(pred.scenario_index, [0, 2])
    alone = prediction_metrics(
        replace(
            pred,
            target_v=pred.target_v[sel],
            pred_v=pred.pred_v[sel],
            mask=pred.mask[sel],
            scenario_index=pred.scenario_index[sel],
        )
    )
    assert by_group[7]["mae_unobs"] == pytest.approx(alone["mae_unobs"])
    assert by_group[9][3]["rel_unobs"] != by_group[7][3]["rel_unobs"]
    with pytest.raises(ValueError, match="scenario_index"):
        prediction_metrics_by_group(replace(pred, scenario_index=None), groups)
